namespace AvClientView;

/// <summary>
/// Shared constants for the View layer.
/// </summary>
public static class ViewConstants
{
    /// <summary>
    /// The design (rendering) resolution width. All UI is laid out
    /// relative to this width; the Viewbox scales it to the physical window.
    /// </summary>
    public const double DesignResolutionWidth = 1280;

    /// <summary>
    /// The design (rendering) resolution height. All UI is laid out
    /// relative to this height; the Viewbox scales it to the physical window.
    /// </summary>
    public const double DesignResolutionHeight = 720;
}
